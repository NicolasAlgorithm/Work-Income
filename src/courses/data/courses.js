const normalizeCourse = (course) => {
  const modules = course.modules.map(([title, lessons], moduleIndex) => ({
    id: `${course.id}-m${moduleIndex + 1}`,
    title,
    lessons: lessons.map(([lessonTitle, minutes, type], lessonIndex) => ({
      id: `${course.id}-m${moduleIndex + 1}-l${lessonIndex + 1}`,
      title: lessonTitle,
      minutes,
      type,
      preview: moduleIndex === 0 && lessonIndex === 0,
    })),
  }))
  const lessons = modules.flatMap((module) => module.lessons)

  return {
    ...course,
    modules,
    lessonIds: lessons.map((lesson) => lesson.id),
    lessonCount: lessons.length,
    totalMinutes: lessons.reduce((total, lesson) => total + lesson.minutes, 0),
  }
}

export const courses = rawCourses.map(normalizeCourse)

export const courseCategories = [...new Set(courses.map((course) => course.category))]

export const courseLevels = ['Basico', 'Intermedio', 'Avanzado']

export const getCourseById = (id) => courses.find((course) => course.id === id)
